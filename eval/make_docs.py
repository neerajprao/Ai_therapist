"""Fill the documents that quote numbers, straight from eval/results/*.json.

  python -m eval.make_docs

Writes docs/MODEL_CARD.md and docs/RESUME_BULLETS.md and replaces the block
between <!-- RESULTS:START --> and <!-- RESULTS:END --> in README.md. Nothing
here is typed by hand: if a result file is missing, the script stops.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "eval" / "results"


def load(name: str) -> dict:
    return json.loads((RESULTS / name).read_text())


def p(x: float, digits: int = 1) -> str:
    return f"{100 * x:.{digits}f}%"


def table(header, rows) -> str:
    return "\n".join(["| " + " | ".join(header) + " |", "|" + "---|" * len(header)] + ["| " + " | ".join(str(c) for c in r) + " |" for r in rows])


def main() -> None:
    inv, sp = load("dataset_inventory.json"), load("splits.json")["split_v2"]
    test, base = load("emotion_test.json"), load("emotion_baseline_v1_repro.json")
    ens, onnx, mem = load("emotion_ensemble.json"), load("onnx_benchmark.json"), load("memory_eval.json")
    cross, lat = load("emotion_cross_corpus_tess.json"), load("latency_local.json")
    cloud = load("latency_cloud.json")
    cttft = cloud["stages"]["time_to_first_token_end_to_end"]
    train, v1 = load("training_main.json"), load("training_v1_repro.json")
    total_min = sum(d.get("train_minutes", d.get("benchmark_wall_seconds", 0) / 60)
                    for d in (json.loads(f.read_text()) for f in RESULTS.glob("training_*.json")))
    v, cmp = onnx["variants"], onnx["int8_vs_pytorch"]
    et, mt = ens["test"], mem["test"]
    best_val = max(h["val_macro_f1"] for h in train["history"])
    v1_leaky = max(h["val_accuracy"] for h in v1["history"])
    stages = lat["stages"]
    import subprocess
    import sys

    collected = subprocess.run([sys.executable, "-m", "pytest", "--collect-only", "-q", "-o", "addopts="], cwd=ROOT, capture_output=True, text=True).stdout
    n_tests = int(re.search(r"(\d+) tests? collected", collected).group(1))

    # ------------------------------------------------------------- README block
    readme_block = "\n".join([
        table(["What", "Result", "Source file"], [
            ["Emotion model, speaker-independent test (Wav2Vec2 alone)", f"{p(test['accuracy'])} accuracy, {p(test['macro_f1'])} macro-F1 on {test['n']} clips from {test['speakers']} unseen speakers", "`emotion_test.json`"],
            ["v1 recipe reproduced, same test set", f"{p(base['accuracy'])} accuracy, {p(base['macro_f1'])} macro-F1", "`emotion_baseline_v1_repro.json`"],
            ["Unseen corpus (trained without TESS, tested on TESS)", f"{p(cross['accuracy'])} accuracy on {cross['n']} clips", "`emotion_cross_corpus_tess.json`"],
            [f"Ensemble with Emotion2Vec (Wav2Vec2 weight {ens['chosen_w2v_weight']})", f"{p(et['chosen']['accuracy'])} accuracy, {p(et['chosen']['macro_f1'])} macro-F1; see caveat", "`emotion_ensemble.json`"],
            ["ONNX INT8 vs PyTorch", f"{v['pytorch_fp32']['size_mb']} MB to {v['onnx_int8']['size_mb']} MB ({cmp['size_reduction_pct']}% smaller); CPU p50 {v['pytorch_fp32']['latency_per_3s_clip']['p50_ms']} ms to {v['onnx_int8']['latency_per_3s_clip']['p50_ms']} ms; macro-F1 {100 * cmp['macro_f1_change']:+.1f} points", "`onnx_benchmark.json`"],
            ["Memory retrieval, held-out half", f"Hit@3 {p(mt['hit_at_3'])}, false recall {p(mt['false_recall_rate'])}, {mem['cross_user_leaks']['leaks']} cross-user leaks", "`memory_eval.json`"],
            ["Local latency, upload to first reply token", f"p50 {stages['time_to_first_token_end_to_end']['p50_ms'] / 1000:.2f} s, p95 {stages['time_to_first_token_end_to_end']['p95_ms'] / 1000:.2f} s over {lat['clips']} clips", "`latency_local.json`"],
            ["Cloud latency (Groq), upload to first reply token", f"p50 {cttft['p50_ms'] / 1000:.2f} s, p95 {cttft['p95_ms'] / 1000:.2f} s over {cloud['clips']} clips, measured from a laptop", "`latency_cloud.json`"],
            ["Tests", f"{n_tests} pytest cases, no model downloads", "`tests/`"],
        ]),
        "",
        "Caveats that matter: the emotion data is acted English speech; the v1 baseline is a reproduction of the old recipe, not the original weights; "
        "Emotion2Vec's training data probably overlaps the test corpora, so the ensemble figure is optimistic; the memory test set is small and synthetic.",
    ])
    readme = ROOT / "README.md"
    text = readme.read_text()
    text = re.sub(r"<!-- RESULTS:START -->.*?<!-- RESULTS:END -->", f"<!-- RESULTS:START -->\n{readme_block}\n<!-- RESULTS:END -->", text, flags=re.S)
    readme.write_text(text)

    # --------------------------------------------------------------- model card
    cfg = train["config"]
    card = f"""# Model card: SoulSync speech emotion classifier (v2)

Generated by `python -m eval.make_docs` from `eval/results/`. Numbers are not typed by hand.

## Summary

A `{cfg['base_model']}` encoder fine-tuned to classify a 3-second speech clip as **happy, sad, angry, neutral or anxious**. Used in SoulSync to give the language model a hint about the speaker's tone. It is a demo component, not a clinical or diagnostic tool.

| | |
|---|---|
| Architecture | Wav2Vec2ForSequenceClassification, CNN feature encoder frozen, {cfg['trainable_params']:,} trainable parameters |
| Input | 16 kHz mono, 3 s, zero-mean unit-variance per clip, zero-padded. Longer audio: 3 s windows with 50% overlap, probabilities averaged |
| Output | 5-way softmax |
| Formats | PyTorch ({v['pytorch_fp32']['size_mb']} MB), ONNX FP32 ({v['onnx_fp32']['size_mb']} MB), ONNX INT8 ({v['onnx_int8']['size_mb']} MB) |

## Data

Four acted, English-language corpora via the Kaggle collection `uldisvalainis/audio-emotions`: {", ".join(f"{c} ({n} files, {inv['speakers_per_corpus'][c]} speakers)" for c, n in inv['files_per_corpus'].items())}. Details and problems found in the packaging: [DATASET.md](DATASET.md).

- "Fearful" is used as "anxious". "Disgusted" and "surprised" are dropped ({inv['dropped_by_source_emotion']}).
- RAVDESS song clips are excluded.
- Labels are read from filenames. The folder labels are wrong for {inv['folder_label_mismatches']['count']} SAVEE clips.

## Split

Speaker-independent, seed 42. Speaker overlap between splits: {sp['speaker_overlap']}.

{table(["Split", "Clips", "Speakers", "By corpus"], [[k, sp[k]['clips'], sp[k]['speakers'], sp[k]['by_corpus']] for k in ("train", "val", "test")])}

TESS has two speakers with 1,000 clips each, so both are in train and the held-out sets contain no TESS.

## Training

| | |
|---|---|
| Optimiser | AdamW, lr {cfg['lr']}, weight decay {cfg['weight_decay']}, {int(cfg['warmup_frac'] * 100)}% warm-up then linear decay |
| Batch size | {cfg['batch_size']}, fp32 on Apple MPS |
| Loss | cross-entropy, class weights {cfg['class_weights']} |
| Augmentation | random 3 s crop for longer clips; Wav2Vec2's built-in time masking |
| Selection | best validation macro-F1, early stopping with patience {cfg['patience']} |
| Result | {train['epochs_completed']} epochs run, best at epoch {train['best_epoch']} (validation macro-F1 {p(best_val)}), {train['train_minutes']} minutes |

Total training wall-clock across all runs in this project: {total_min:.1f} minutes.

## Metrics

Test split: {test['n']} clips, {test['speakers']} speakers never seen in training. Scored once.

| Metric | Value | 95% CI (clip bootstrap) |
|---|---|---|
| Accuracy | {p(test['accuracy'])} | {p(test['accuracy_ci95'][0])} to {p(test['accuracy_ci95'][1])} |
| Macro-F1 | {p(test['macro_f1'])} | {p(test['macro_f1_ci95'][0])} to {p(test['macro_f1_ci95'][1])} |

{table(["Class", "Precision", "Recall", "F1", "Support"], [[c, p(m['precision']), p(m['recall']), p(m['f1']), m['support']] for c, m in test['per_class'].items()])}

By corpus: {", ".join(f"{c} {p(m['accuracy'])} (n={m['n']})" for c, m in test['by_corpus'].items())}. Per-speaker accuracy ranges from {p(test['per_speaker_accuracy']['min'])} to {p(test['per_speaker_accuracy']['max'])}.

![Confusion matrix](../eval/results/emotion_test.png)

### How much to trust these numbers

- The confidence intervals resample clips. They do not cover seed-to-seed variation (one training run) or the fact that there are only {test['speakers']} test speakers.
- Validation macro-F1 was {p(best_val)} and test macro-F1 is {p(test['macro_f1'])}. The gap shows how much results move between two sets of 14 speakers.
- Trained without TESS and tested on TESS (an unseen corpus, 2 unseen speakers): {p(cross['accuracy'])} accuracy, {p(cross['macro_f1'])} macro-F1 on {cross['n']} clips.

### Baseline

The v1 notebook's recipe (RAVDESS only, split by file, `wav2vec2-base-960h`) was reproduced because the original weights were unavailable. It scores {p(v1_leaky)} on its own file-level validation split and {p(base['accuracy'])} accuracy ({p(base['macro_f1'])} macro-F1) on this test set. The original notebook reported 82.9% on its leaky validation split, so the reproduction is weaker than the original model was and the "before" figure is likely pessimistic.

### Emotion2Vec and the ensemble

v1 discarded every Emotion2Vec score through a label mismatch. With the mapping fixed, on the same test set: Emotion2Vec alone {p(et['emotion2vec_alone']['accuracy'])} accuracy; ensemble at Wav2Vec2 weight {ens['best_on_val']['w2v_weight']} {p(et['best_val_weight_for_reference']['accuracy'])}. The weight was chosen on validation (macro-F1 gain {100 * ens['val_gain_over_w2v_alone']:+.1f} points, 95% CI {100 * ens['val_gain_ci95'][0]:+.1f} to {100 * ens['val_gain_ci95'][1]:+.1f}).

**Read this number with care.** Emotion2Vec is a public model fine-tuned on EmoBox, a collection of academic emotion corpora. If that includes RAVDESS, CREMA-D or SAVEE, it has heard our test speakers, and its score here is not a speaker-independent result. Nearly all of the ensemble's accuracy comes from Emotion2Vec; the fine-tuned Wav2Vec2 adds little on top of it.

### Quantisation

{table(["Version", "Size", "Accuracy", "Macro-F1", "CPU p50 / p95 per 3 s clip"], [[k, f"{m['size_mb']} MB", p(m['accuracy']), p(m['macro_f1']), f"{m['latency_per_3s_clip']['p50_ms']} / {m['latency_per_3s_clip']['p95_ms']} ms"] for k, m in v.items()])}

## Limitations

- **Acted speech.** Actors reading fixed sentences exaggerate emotion. Performance on spontaneous speech is unmeasured and expected to be lower.
- **English only.** Mostly North American and British speakers.
- **Five coarse classes.** "Anxious" is a relabelled "fearful". Real anxiety rarely sounds like acted fear.
- **Short clips.** Trained on 3-second windows of single sentences.
- **Not a clinical tool.** It must not be used to assess mental state, risk or diagnosis. In SoulSync it only adjusts the tone of a reply, and the UI says the estimate is often wrong.
- **One seed, one run.**

## Licences

RAVDESS: CC BY-NC-SA 4.0. CREMA-D: ODbL 1.0 (contents DbCL 1.0). TESS: CC BY-NC 4.0. SAVEE: registration licence, no redistribution. Base model `facebook/wav2vec2-base`: Apache-2.0. Checked against the source pages on 2026-10-14; details in [DATASET.md](DATASET.md). Because two corpora are non-commercial, treat these weights as non-commercial research output.
"""
    (ROOT / "docs" / "MODEL_CARD.md").write_text(card)

    # ----------------------------------------------------------- resume bullets
    ttft = stages["time_to_first_token_end_to_end"]
    bullets = f"""# Resume bullets for SoulSync

Generated by `python -m eval.make_docs`. Every number below is read from the file named under the bullet.

**SoulSync: voice-first AI companion with emotion recognition and long-term memory** (Python, PyTorch, FastAPI)

- Fine-tuned Wav2Vec2 for 5-class speech emotion recognition on {sp['train']['clips']:,} clips from 4 corpora, reaching {p(test['macro_f1'])} macro-F1 on {test['speakers']} held-out speakers after replacing a leaky file-level split with a speaker-independent one and correcting {inv['folder_label_mismatches']['count']} mislabelled clips found in the source dataset.
  - Proof: `eval/results/emotion_test.json`, `eval/results/splits.json`, `eval/results/dataset_inventory.json`

- Exported the classifier to ONNX with INT8 dynamic quantization, cutting model size {cmp['size_reduction_pct']}% ({v['pytorch_fp32']['size_mb']} MB to {v['onnx_int8']['size_mb']} MB) with a {100 * cmp['macro_f1_change']:+.1f}-point change in macro-F1 and CPU p50 latency of {v['onnx_int8']['latency_per_3s_clip']['p50_ms']} ms per 3 s clip, so the cloud build runs without PyTorch.
  - Proof: `eval/results/onnx_benchmark.json`

- Built per-user RAG memory with ChromaDB and MiniLM embeddings (semantic search with a tuned cosine-distance threshold), scoring Hit@3 of {p(mt['hit_at_3'], 0)} and {p(mt['false_recall_rate'], 0)} false recall on a held-out synthetic test set with {mem['cross_user_leaks']['leaks']} cross-user leaks.
  - Proof: `eval/results/memory_eval.json`

- Shipped a streaming FastAPI backend with a local LLM (Qwen 2.5 via Ollama) and a Groq cloud mode (Whisper large-v3 turbo + Qwen), a crisis-language safety layer, {n_tests} pytest cases and GitHub Actions CI; measured p50 of {ttft['p50_ms'] / 1000:.1f} s locally and {cttft['p50_ms'] / 1000:.1f} s via Groq from voice upload to first reply token.
  - Proof: `eval/results/latency_local.json`, `eval/results/latency_cloud.json`, `tests/`, `.github/workflows/tests.yml`

## Notes before you use these

- The {p(test['macro_f1'])} figure is on **acted** speech. If asked, say so; it is the honest speaker-independent number and it is the one to quote.
- Do not quote the ensemble figure ({p(et['chosen']['accuracy'])}) as your model's accuracy. Most of it comes from the pretrained Emotion2Vec model, whose training data probably overlaps the test corpora.
- Do not claim an improvement "from 83%". The 83% was a leaky validation score. The reproduced v1 recipe scores {p(base['accuracy'])} on the new test set, but that reproduction is weaker than your original model, so avoid a before/after claim altogether.
- "Docker" is not in the bullets because the image has not been built or measured. Add it after a real build.
- The Groq latency was measured from a laptop over a home connection, not from a deployed server.
- The memory test set has {mt['n_followups']} held-out follow-ups and {mt['n_unrelated']} unrelated questions, written by you. Call it a synthetic test set if asked.
"""
    (ROOT / "docs" / "RESUME_BULLETS.md").write_text(bullets)
    print("updated README.md results block, docs/MODEL_CARD.md, docs/RESUME_BULLETS.md")


if __name__ == "__main__":
    main()
